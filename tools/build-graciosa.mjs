import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileOverpass, FRAME } from './graciosa-geo.mjs';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const CACHE = path.join(ROOT, 'data', 'osm_graciosa.json');
const OUTPUT = path.join(ROOT, '..', 'js', 'graciosa-geodata.js');
const QUERY = await fs.readFile(path.join(ROOT, 'data', 'q_graciosa.overpassql'), 'utf8');
const ENDPOINTS = [
  'https://overpass-api.de/api/interpreter',
  'https://lz4.overpass-api.de/api/interpreter',
  'https://z.overpass-api.de/api/interpreter'
];

async function fetchSnapshot() {
  let lastError;
  for (const endpoint of ENDPOINTS) {
    try {
      const response = await fetch(endpoint, {
        method: 'POST',
        headers: {
          'content-type': 'application/x-www-form-urlencoded',
          accept: 'application/json',
          'user-agent': 'slop-graciosa-island/1.0 (OpenStreetMap data download)'
        },
        body: new URLSearchParams({ data: QUERY }),
        signal: AbortSignal.timeout(240000)
      });
      if (!response.ok) throw new Error(`Overpass returned HTTP ${response.status}`);
      const snapshot = await response.json();
      if (!Array.isArray(snapshot.elements) || snapshot.remark) throw new Error('Overpass returned incomplete data.');
      await fs.writeFile(CACHE, `${JSON.stringify(snapshot)}\n`);
      console.log(`[graciosa] downloaded ${snapshot.elements.length} OSM elements from ${endpoint}`);
      return snapshot;
    } catch (error) {
      lastError = error;
      console.warn(`[graciosa] ${endpoint}: ${error.message}`);
    }
  }
  throw new Error('Unable to fetch a complete Overpass snapshot from the available endpoints.', { cause: lastError });
}

const snapshot = process.argv.includes('--fetch')
  ? await fetchSnapshot()
  : JSON.parse(await fs.readFile(CACHE, 'utf8'));
const geodata = compileOverpass(snapshot);
const output = `// Generated by tools/build-graciosa.mjs; do not edit.\n// OpenStreetMap contributors, ODbL 1.0; Overpass bbox ${FRAME.bounds.south},${FRAME.bounds.west},${FRAME.bounds.north},${FRAME.bounds.east}.\nexport const GEO = ${JSON.stringify(geodata)};\n`;
await fs.writeFile(OUTPUT, output);
console.log(`[graciosa] ${geodata.buildings.length} buildings, ${geodata.roads.length} roads, ${geodata.harborStructures.length} mapped harbor structures, ${geodata.coast.length} coastlines`);
console.log(`[graciosa] wrote ${path.relative(path.join(ROOT, '..'), OUTPUT)} (${Buffer.byteLength(output)} bytes)`);
